"""Build the web calculator's data file (docs/opci_data.js) from the latest data release
and location/factors.csv.

The page (docs/index.html) holds no numbers of its own. This script copies the index
values from the newest folder in data/releases and the full location table, unchanged,
into one JavaScript file the page loads. The monthly refresh workflow runs it after
each new data release.

Run:  python -m scripts.build_calculator_data [--out docs/opci_data.js]
"""
import argparse
import json
import sys
from pathlib import Path

from opci import CREDIT, __version__, paths
from opci.locations import load_factors, version as location_version
from opci.release import list_releases, read_release

OUT = paths.REPO / "docs" / "opci_data.js"


def build(release=None):
    """Return the calculator data as a dict. Uses the latest release unless one is named."""
    name = release or list_releases()[-1].name
    annual, quarterly = read_release(name, "annual"), read_release(name, "quarterly")
    meta = annual["meta"]
    locations = [
        {k: r[k] for k in ("code", "name", "factor", "low", "high", "confidence", "method", "notes")}
        for r in load_factors().values()
    ]
    return {
        "release": name,
        "version": __version__,
        "location_version": location_version(),
        "credit": CREDIT,
        "data_to": meta["data_to"],
        # Part periods, e.g. {"2026": "2026 is a part year (January to September average)."}
        "part_notes": {n.split()[0]: n for n in meta["notes"] + quarterly["meta"]["notes"]},
        "annual": [{"period": r["period"], "value": r["value"], "part": r["part"],
                    "supply_shock": r["supply_shock"]} for r in annual["rows"]],
        "quarterly": [{"period": r["period"], "value": r["value"], "part": r["part"],
                       "supply_shock": r["supply_shock"]} for r in quarterly["rows"]],
        "locations": locations,
    }


def render(data):
    return ("// Generated by scripts/build_calculator_data.py from data/releases/"
            f"{data['release']} and location/factors.csv. Do not edit by hand.\n"
            f"window.OPCI_DATA = {json.dumps(data, indent=1)};\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build docs/opci_data.js for the web calculator.")
    ap.add_argument("--release", default=None, help="data release name (default: the latest)")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    data = build(args.release)
    Path(args.out).write_text(render(data), encoding="utf-8", newline="\n")
    print(f"Calculator data written: {args.out} (release {data['release']}, OPCI v{data['version']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
